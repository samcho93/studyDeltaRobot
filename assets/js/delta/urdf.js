// urdf.js — URDF generator. Mirror of python/deltarobot/urdf.py: the output text must be identical.
import { PHI, fk, passiveAngles } from './kinematics.js';

const HALF_PI = Math.PI / 2;
export const GRIPPER_STROKE = 0.006;    // finger travel per side [m]; open = 0, closed = -GRIPPER_STROKE
const GRIPPER_FINGER_X = 0.015;

export function f(v) {
  let s = Number(v).toFixed(6);
  s = s.replace(/0+$/, '').replace(/\.$/, '');
  return (s === '-0' || s === '') ? '0' : s;
}
const xyz = (...v) => v.map(f).join(' ');

const inertial = (mass, o, ixx, iyy, izz) => [
  '    <inertial>',
  `      <origin xyz="${xyz(...o)}" rpy="0 0 0"/>`,
  `      <mass value="${f(mass)}"/>`,
  `      <inertia ixx="${f(ixx)}" ixy="0" ixz="0" iyy="${f(iyy)}" iyz="0" izz="${f(izz)}"/>`,
  '    </inertial>'];
const cyl = (o, rpy, radius, length, mat) => [
  '    <visual>',
  `      <origin xyz="${xyz(...o)}" rpy="${xyz(...rpy)}"/>`,
  `      <geometry><cylinder radius="${f(radius)}" length="${f(length)}"/></geometry>`,
  `      <material name="${mat}"/>`,
  '    </visual>'];
const sphere = (o, radius, mat) => [
  '    <visual>',
  `      <origin xyz="${xyz(...o)}" rpy="0 0 0"/>`,
  `      <geometry><sphere radius="${f(radius)}"/></geometry>`,
  `      <material name="${mat}"/>`,
  '    </visual>'];
const box = (o, size, mat) => [
  '    <visual>',
  `      <origin xyz="${xyz(...o)}" rpy="0 0 0"/>`,
  `      <geometry><box size="${xyz(...size)}"/></geometry>`,
  `      <material name="${mat}"/>`,
  '    </visual>'];

function joint(name, kind, parent, child, o, rpy = [0, 0, 0], axis = null, limit = null, mimic = '') {
  const out = [`  <joint name="${name}" type="${kind}">`, `    <parent link="${parent}"/>`,
    `    <child link="${child}"/>`, `    <origin xyz="${xyz(...o)}" rpy="${xyz(...rpy)}"/>`];
  if (axis) out.push(`    <axis xyz="${xyz(...axis)}"/>`);
  if (limit) out.push(`    <limit lower="${f(limit[0])}" upper="${f(limit[1])}" effort="${f(limit[2])}" velocity="${f(limit[3])}"/>`);
  if (mimic) out.push(`    <mimic joint="${mimic}" multiplier="1" offset="0"/>`);
  out.push('  </joint>');
  return out;
}

export function generate(d, name = 'delta_robot') {
  const R = d.base_radius, r = d.effector_radius, L = d.upper_arm, l = d.forearm, w = d.forearm_spacing;
  const tool = d.toolSpec, tl = d.toolLength;
  const armR = Math.max(0.006, 0.05 * L);
  const rodR = Math.max(0.003, 0.012 * l);
  const motorR = Math.min(0.05, Math.max(0.014, 0.18 * R));
  const motorLen = Math.min(0.12, Math.max(0.03, 0.35 * R));
  const reach = R - r + L + l;
  const effort = Number(d.motorSpec.peak_torque) * d.ratio * d.efficiency;
  const vel = Number(d.motorSpec.max_speed) / d.ratio;

  const x = ['<?xml version="1.0"?>',
    `<!-- generated by deltarobot.urdf — R=${f(R)} r=${f(r)} L=${f(L)} l=${f(l)} w=${f(w)} motor=${d.motor} tool=${d.tool} -->`,
    `<robot name="${name}">`];
  for (const [mat, rgba] of [['frame', '0.55 0.6 0.68 1'], ['motor', '0.15 0.17 0.2 1'], ['arm', '0.9 0.55 0.15 1'],
    ['rod', '0.12 0.12 0.14 1'], ['joint', '0.75 0.78 0.82 1'], ['plate', '0.25 0.55 0.9 1'], ['tool', '0.2 0.75 0.5 1']]) {
    x.push(`  <material name="${mat}"><color rgba="${rgba}"/></material>`);
  }
  x.push('  <link name="base_link">');
  x.push(...cyl([0, 0, 0.02 + 0.006], [0, 0, 0], R + motorR + 0.01, 0.012, 'frame'));
  for (let i = 0; i < 3; i++) {
    const phi = PHI[i];
    x.push(...cyl([R * Math.cos(phi), R * Math.sin(phi), 0], [HALF_PI, 0, phi], motorR, motorLen, 'motor'));
  }
  x.push(...inertial(3 * Number(d.motorSpec.mass) + 0.5, [0, 0, 0.02], 0.01, 0.01, 0.02));
  x.push('  </link>');

  for (let i = 0; i < 3; i++) {
    const n = i + 1, phi = PHI[i];
    x.push(...joint(`motor${n}_joint`, 'revolute', 'base_link', `upper_arm${n}`,
      [R * Math.cos(phi), R * Math.sin(phi), 0], [0, 0, phi], [0, 1, 0], [d.theta_min, d.theta_max, effort, vel]));
    const m = d.upperArmMass;
    x.push(`  <link name="upper_arm${n}">`);
    x.push(...cyl([L / 2, 0, 0], [0, HALF_PI, 0], armR, L, 'arm'));
    x.push(...cyl([L, 0, 0], [HALF_PI, 0, 0], armR * 0.8, w + 2 * armR, 'arm'));
    x.push(...inertial(m + d.elbowMass, [L / 2, 0, 0], 1e-5, m * L * L / 12, m * L * L / 12));
    x.push('  </link>');
    for (const [k, sgn] of [['a', 1], ['b', -1]]) {
      const mp = k === 'a' ? '' : `elbow${n}a_pitch`;
      const my = k === 'a' ? '' : `elbow${n}a_yaw`;
      x.push(...joint(`elbow${n}${k}_pitch`, 'revolute', `upper_arm${n}`, `elbow${n}${k}_link`,
        [L, sgn * w / 2, 0], [0, 0, 0], [0, 1, 0], [-Math.PI, Math.PI, 0, 0], mp));
      x.push(`  <link name="elbow${n}${k}_link"/>`);
      x.push(...joint(`elbow${n}${k}_yaw`, 'revolute', `elbow${n}${k}_link`, `forearm${n}${k}`,
        [0, 0, 0], [0, 0, 0], [0, 0, 1], [-HALF_PI, HALF_PI, 0, 0], my));
      const mr = d.forearmPairMass / 2;
      x.push(`  <link name="forearm${n}${k}">`);
      x.push(...cyl([l / 2, 0, 0], [0, HALF_PI, 0], rodR, l, 'rod'));
      x.push(...sphere([0, 0, 0], rodR * 1.8, 'joint'));
      x.push(...sphere([l, 0, 0], rodR * 1.8, 'joint'));
      x.push(...inertial(mr, [l / 2, 0, 0], 1e-6, mr * l * l / 12, mr * l * l / 12));
      x.push('  </link>');
    }
  }

  x.push(...joint('effector_x', 'prismatic', 'base_link', 'effector_x_link', [0, 0, 0], [0, 0, 0], [1, 0, 0], [-reach, reach, 0, 0]));
  x.push('  <link name="effector_x_link"/>');
  x.push(...joint('effector_y', 'prismatic', 'effector_x_link', 'effector_y_link', [0, 0, 0], [0, 0, 0], [0, 1, 0], [-reach, reach, 0, 0]));
  x.push('  <link name="effector_y_link"/>');
  x.push(...joint('effector_z', 'prismatic', 'effector_y_link', 'effector', [0, 0, 0], [0, 0, 0], [0, 0, 1], [-(L + l), 0, 0, 0]));
  x.push('  <link name="effector">');
  x.push(...cyl([0, 0, 0], [0, 0, 0], r + 0.012, 0.01, 'plate'));
  x.push(...inertial(d.effector_mass, [0, 0, 0], 1e-4, 1e-4, 2e-4));
  x.push('  </link>');
  x.push(...joint('tool_joint', 'fixed', 'effector', 'tool_link', [0, 0, -0.005]));
  x.push('  <link name="tool_link">');
  const kind = tool.kind;
  if (kind === 'suction') {
    const cup = Math.max(0.01, Math.sqrt(Number(tool.force) / 60e3 / Math.PI));
    x.push(...cyl([0, 0, -(tl - 0.008) / 2], [0, 0, 0], 0.006, tl - 0.008, 'tool'));
    x.push(...cyl([0, 0, -tl + 0.004], [0, 0, 0], cup, 0.008, 'tool'));
  } else if (kind === 'gripper') {
    x.push(...box([0, 0, -0.015], [0.06, 0.03, 0.03], 'tool'));      // fingers are child links (below)
  } else if (kind === 'magnet') {
    x.push(...cyl([0, 0, -tl / 2], [0, 0, 0], 0.0125, tl, 'tool'));
  } else {
    x.push(...cyl([0, 0, -tl / 2], [0, 0, 0], 0.004, tl, 'tool'));
  }
  x.push(...inertial(Math.max(1e-3, Number(tool.mass)), [0, 0, -tl / 2], 1e-5, 1e-5, 1e-5));
  x.push('  </link>');
  if (kind === 'gripper') {
    const grip = Number(tool.force);
    for (const [k, sgn] of [['a', 1], ['b', -1]]) {
      x.push(...joint(`gripper_finger_${k}`, 'prismatic', 'tool_link', `gripper_finger_${k}_link`,
        [sgn * GRIPPER_FINGER_X, 0, 0], [0, 0, 0], [sgn, 0, 0], [-GRIPPER_STROKE, 0, grip, 0.05], k === 'a' ? '' : 'gripper_finger_a'));
      x.push(`  <link name="gripper_finger_${k}_link">`);
      x.push(...box([0, 0, -(tl + 0.03) / 2], [0.006, 0.02, tl - 0.03], 'tool'));
      x.push(...inertial(0.01, [0, 0, -(tl + 0.03) / 2], 1e-6, 1e-6, 1e-6));
      x.push('  </link>');
    }
  }
  x.push(...joint('tcp_joint', 'fixed', 'tool_link', 'tcp', [0, 0, -tl + 0.005]));
  x.push('  <link name="tcp"/>');
  x.push('</robot>');
  return x.join('\n') + '\n';
}

export const ACTIVE = ['motor1_joint', 'motor2_joint', 'motor3_joint'];

export function jointState(d, theta, tool = 0) {
  const p = fk(d, theta);
  const out = {};
  for (let i = 0; i < 3; i++) out[`motor${i + 1}_joint`] = theta[i];
  passiveAngles(d, theta, p).forEach(([pitch, yaw], i) => {
    out[`elbow${i + 1}a_pitch`] = pitch;
    out[`elbow${i + 1}a_yaw`] = yaw;
  });
  out.effector_x = p[0]; out.effector_y = p[1]; out.effector_z = p[2];
  if (d.toolSpec.kind === 'gripper') out.gripper_finger_a = tool ? -GRIPPER_STROKE : 0;
  return out;
}
